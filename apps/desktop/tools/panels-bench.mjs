// End-to-end benchmark for panels (`npm run bench:panels`, an optional check in development flow §2; the M12 baseline in acceptance and testing §4 is measured with it): the real UI
// (the renderer's production build from `electron-vite build`, served as-is by a local HTTP server) connects in headless Chrome to an isolated Runtime, opens programmatically synthesized large and small videos, and measures the mounted counts of captions, translation, the script list and the timeline, the frame intervals of continuous scrolling, tab switching, one timeline zoom step and fit-to-view, and replacing and undoing all captions.
//
// Setup: the temp directories (Home, projects, downloads, media, Chrome's user data) are created in the system temp directory and deleted at the end (including on failure and signals), so nothing is left in the repo.
// Media is generated by ffmpeg (a small solid-color frame plus silence, duration set per tier to match the M12 baseline fixtures and not shorter than the transcript). The isolated Runtime
// (`panels-bench-runtime.mts`: no agents registered, no keychain access, no LAN node discovery, and the gateway admits only the one origin of the local HTTP server) builds each tier's project and video.
// The host bridge and measurement helpers are injected by CDP before the page scripts (`panels-bench-page.mjs`); Typekit requests are blocked, and other non-local requests are only recorded and reported.
// Each tier is loaded fresh N times (navigating again in the same Chrome). Before each load, it waits up to 1 minute for the load average to drop below 3 (checked every 10 seconds, for at most 3 minutes; if it never drops it measures anyway), then runs the full measurement pass. At the end it reports the environment, the size of each tier, and a table mapping rows one-to-one to the M12 baseline in acceptance spec §4 (the range across the fresh loads).
//
// Usage: node apps/desktop/tools/panels-bench.mjs [--tier small|big]... (defaults to both tiers, small first) [--runs 3] [--window 1440x900]
//        [--json <output file>] (raw results and environment of each run)
// Environment: CUCCUT_ENGINE_HOST (defaults to CARGO_TARGET_DIR, or debug/engine-host under the repo's target), CUCCUT_FFMPEG / CUCCUT_FFPROBE,
//        CUCCUT_CHROME (defaults to Google Chrome under /Applications, then google-chrome or chromium on PATH).
// Exit codes: 0 finished, 1 one of the fresh loads did not finish, 2 timed out or failed to start.

import { spawn, spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { cpus, loadavg, platform, release, tmpdir, totalmem, type } from 'node:os';
import { dirname, extname, join, resolve, sep } from 'node:path';
import { createInterface } from 'node:readline';
import { fileURLToPath } from 'node:url';
import { hostBridgeSource, installHelpers, runSuite } from './panels-bench-page.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const RENDERER = resolve(HERE, '../out/renderer');
const ROOT = resolve(HERE, '../../..');
/** Time limit for one fresh load (from opening the video to the end of the full measurement pass). */
const RUN_TIMEOUT_MS = 20 * 60_000;
/** Waiting for load to drop before a load: threshold, interval, upper limit. */
const LOAD_LIMIT = 3;
const LOAD_POLL_MS = 10_000;
const LOAD_WAIT_MS = 3 * 60_000;

/**
 * The size of the two tiers: the caption sentence count, the number of video clips on the timeline (cut points plus one), the number of dub blocks, and the media length (seconds).
 * The media is longer than the transcript (the transcript is about 35:55 and 2:59:35); as with the M12 baseline fixtures, the clip lengths after cutting are 44:00 and 3:40:00.
 * The clip length sets the timeline width at 100% and the spacing of the dub blocks, and the mount counts follow it; changing it would no longer match the baseline.
 */
const TIERS = {
  small: { label: '小档', cues: 1000, clips: 200, dubs: 200, mediaSeconds: 45 * 60 },
  big: { label: '大档', cues: 5000, clips: 1000, dubs: 1000, mediaSeconds: 3 * 3600 + 45 * 60 },
};

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript',
  '.css': 'text/css',
  '.wasm': 'application/wasm',
  '.ttf': 'font/ttf',
  '.woff2': 'font/woff2',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.json': 'application/json',
};

function parseOptions(argv) {
  const options = { tiers: [], runs: 3, window: { width: 1440, height: 900 }, json: null };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    if (arg === '--tier') {
      const tier = argv[++i];
      if (!TIERS[tier]) throw new Error(`--tier must be ${Object.keys(TIERS).join(' or ')}`);
      if (!options.tiers.includes(tier)) options.tiers.push(tier);
    } else if (arg === '--runs') options.runs = Number(argv[++i]);
    else if (arg === '--window') {
      const [width, height] = argv[++i].split('x').map(Number);
      options.window = { width, height };
    } else if (arg === '--json') options.json = resolve(argv[++i]);
    else throw new Error(`Unknown argument ${arg}`);
  }
  if (options.tiers.length === 0) options.tiers = ['small', 'big'];
  else options.tiers.sort((a, b) => Object.keys(TIERS).indexOf(a) - Object.keys(TIERS).indexOf(b));
  if (!(options.runs >= 1)) throw new Error('--runs must be at least 1');
  return options;
}

/** Transcript length (seconds): the same algorithm as in `panels-bench-runtime.mts` (sentence lengths cycle through 3–10 words, each word 0.27 s, 0.4 s between sentences, starting at 0.3 s). */
function transcriptSeconds(cues) {
  let t = 0.3;
  for (let s = 0; s < cues; s++) t += (3 + ((s * 7) % 8)) * 0.27 + 0.4;
  return t;
}

const options = (() => {
  try {
    return parseOptions(process.argv.slice(2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exit(2);
  }
})();

// —— Cleanup: temp directories, Chrome, Runtime, HTTP server; every exit path goes through this ——
const children = [];
let temp = null;
let server = null;
let cleaned = false;
function cleanup() {
  if (cleaned) return;
  cleaned = true;
  for (const child of children) if (child.exitCode === null && child.signalCode === null) child.kill('SIGTERM');
  server?.close();
  server?.closeAllConnections?.();
  if (temp) {
    // The Runtime and Chrome still write a few more things after receiving a signal, so wait for them to exit first; if deleting the directory left it non-empty, delete it again.
    const deadline = Date.now() + 5000;
    while (children.some((c) => c.exitCode === null && c.signalCode === null) && Date.now() < deadline) spawnSync('sleep', ['0.1']);
    for (const child of children) if (child.exitCode === null && child.signalCode === null) child.kill('SIGKILL');
    rmSync(temp, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
  }
}
function exit(code) {
  cleanup();
  process.exit(code);
}
process.on('exit', cleanup);
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => exit(2));
process.on('unhandledRejection', (error) => {
  console.error(error);
  exit(2);
});

main().catch((error) => {
  console.error(error);
  exit(2);
});

async function main() {
  if (!existsSync(join(RENDERER, 'index.html'))) {
    console.error(`Missing ${join(RENDERER, 'index.html')}: run npm run build first`);
    exit(2);
  }
  const engineHost = process.env.CUCCUT_ENGINE_HOST || join(process.env.CARGO_TARGET_DIR || join(ROOT, 'target'), 'debug/engine-host');
  if (!existsSync(engineHost)) {
    console.error(`Missing ${engineHost}: run cargo build -p engine-host first, or set CUCCUT_ENGINE_HOST`);
    exit(2);
  }
  const chromeBinary = findChrome();
  if (!chromeBinary) {
    console.error('Chrome not found: install Google Chrome, or set the executable with CUCCUT_CHROME');
    exit(2);
  }
  const ffmpeg = process.env.CUCCUT_FFMPEG || 'ffmpeg';
  const ffprobe = process.env.CUCCUT_FFPROBE || 'ffprobe';

  temp = mkdtempSync(join(tmpdir(), 'cuccut-panels-bench-'));
  const dirs = {
    home: join(temp, 'home'),
    projects: join(temp, 'projects'),
    downloads: join(temp, 'downloads'),
    media: join(temp, 'media'),
    chrome: join(temp, 'chrome-profile'),
  };
  for (const dir of Object.values(dirs)) mkdirSync(dir);

  // Media: a small solid-color frame plus silence, duration set per tier (not shorter than the transcript). After generating, check with ffprobe that the duration is long enough.
  const tiers = [];
  for (const key of options.tiers) {
    const tier = TIERS[key];
    const need = transcriptSeconds(tier.cues);
    const seconds = tier.mediaSeconds;
    if (seconds < need) throw new Error(`${tier.label} media is ${seconds} s, shorter than the ${need.toFixed(1)} s transcript`);
    const file = join(dirs.media, `panels-${key}.mp4`);
    const started = Date.now();
    const made = spawnSync(ffmpeg, [
      ...['-v', 'error', '-f', 'lavfi', '-i', `color=c=0x303840:s=160x90:r=30:d=${seconds}`],
      ...['-f', 'lavfi', '-i', `anullsrc=r=48000:cl=stereo:d=${seconds}`],
      ...['-c:v', 'libx264', '-preset', 'ultrafast', '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-shortest', file],
    ]);
    if (made.error || made.status !== 0) throw new Error(`ffmpeg failed to generate ${tier.label} media: ${made.error?.message ?? made.stderr}`);
    const probed = spawnSync(ffprobe, ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', file], { encoding: 'utf8' });
    const duration = Number(probed.stdout.trim());
    if (probed.status !== 0 || !(duration >= need)) {
      throw new Error(`${tier.label} media is ${probed.stdout.trim() || probed.stderr} s long, not enough for the ${need.toFixed(1)} s transcript`);
    }
    console.error(
      `${tier.label} media ${duration.toFixed(1)} s (transcript ${need.toFixed(1)} s), generated in ${((Date.now() - started) / 1000).toFixed(1)} s`,
    );
    tiers.push({ key, ...tier, media: file, mediaSeconds: duration });
  }

  // The local HTTP server starts first: the Runtime's gateway needs to know the origin to admit (the port).
  server = createServer((request, response) => {
    const rel = decodeURIComponent(new URL(request.url ?? '/', 'http://x').pathname);
    const file = resolve(RENDERER, `.${rel === '/' ? '/index.html' : rel}`);
    if (!file.startsWith(RENDERER + sep) || !existsSync(file) || !statSync(file).isFile()) {
      response.statusCode = 404;
      response.end();
      return;
    }
    response.setHeader('content-type', MIME[extname(file)] ?? 'application/octet-stream');
    response.end(readFileSync(file));
  });
  await new Promise((done, fail) => server.once('error', fail).listen(0, '127.0.0.1', done));
  const origin = `http://127.0.0.1:${server.address().port}`;

  const env = {
    ...process.env,
    CUCCUT_HOME: dirs.home,
    CUCCUT_PROJECTS_DIR: dirs.projects,
    CUCCUT_DOWNLOADS_DIR: dirs.downloads,
    CUCCUT_ENGINE_HOST: engineHost,
    // Find PATH without a login shell (shell config is not run): ffprobe / ffmpeg use the current PATH or CUCCUT_FFPROBE / CUCCUT_FFMPEG.
    SHELL: '/usr/bin/false',
  };
  delete env.ELECTRON_RUN_AS_NODE;
  delete env.ELECTRON_RENDERER_URL;
  const spec = tiers.map((t) => ({
    tier: t.key,
    project: `panels-${t.key}`,
    video: t.label,
    media: t.media,
    cues: t.cues,
    clips: t.clips,
    dubs: t.dubs,
  }));
  const runtime = spawn(process.execPath, [join(HERE, 'panels-bench-runtime.mts'), '--tiers', JSON.stringify(spec), '--origin', origin], {
    env,
    stdio: ['ignore', 'pipe', 'inherit'],
  });
  children.push(runtime);
  const started = Date.now();
  const ready = await new Promise((done) => {
    const timer = setTimeout(() => done(null), 10 * 60_000);
    runtime.on('exit', () => done(null));
    createInterface({ input: runtime.stdout }).on('line', (line) => {
      try {
        const message = JSON.parse(line);
        if (message.type === 'ready') {
          clearTimeout(timer);
          done(message);
        }
      } catch {
        // Not the ready message; ignore it.
      }
    });
  });
  if (!ready) {
    console.error('The isolated Runtime did not start');
    exit(2);
  }
  console.error(`Runtime ready, fixture build took ${((Date.now() - started) / 1000).toFixed(1)} s`);
  for (const t of tiers) t.scale = ready.tiers.find((s) => s.tier === t.key);
  const discovery = JSON.parse(readFileSync(join(dirs.home, 'runtime.json'), 'utf8'));

  // Headless Chrome: Chrome picks the debugging port itself (written to DevToolsActivePort in the user directory), so no fixed port is taken.
  const chrome = spawn(
    chromeBinary,
    [
      '--headless=new',
      '--remote-debugging-port=0',
      `--user-data-dir=${dirs.chrome}`,
      `--window-size=${options.window.width},${options.window.height}`,
      '--no-first-run',
      '--no-default-browser-check',
      '--lang=zh-CN',
      'about:blank',
    ],
    { stdio: 'ignore' },
  );
  children.push(chrome);
  const portFile = join(dirs.chrome, 'DevToolsActivePort');
  for (let i = 0; i < 300 && !(existsSync(portFile) && readFileSync(portFile, 'utf8').includes('\n')); i++) await sleep(100);
  if (!existsSync(portFile)) {
    console.error('Chrome did not start (no DevToolsActivePort)');
    exit(2);
  }
  const debugPort = readFileSync(portFile, 'utf8').split('\n')[0];
  const targets = await (await fetch(`http://127.0.0.1:${debugPort}/json/list`)).json();
  const target = targets.find((t) => t.type === 'page');
  if (!target) {
    console.error('No page in Chrome');
    exit(2);
  }
  const page = await connect(target.webSocketDebuggerUrl);
  const version = await page.send('Browser.getVersion');

  // Non-local requests: Typekit is blocked, the rest are recorded and reported (the page should only connect to localhost).
  const external = new Set();
  let typekit = 0;
  page.on('Network.requestWillBeSent', ({ request }) => {
    if (/^(data|blob):/.test(request.url) || /^(https?|wss?):\/\/127\.0\.0\.1[:/]/.test(request.url)) return;
    if (/typekit/.test(request.url)) typekit++;
    else external.add(request.url);
  });
  await page.send('Network.enable');
  await page.send('Network.setBlockedURLs', { urls: ['*typekit*'] });
  await page.send('Page.enable');
  await page.send('Emulation.setLocaleOverride', { locale: 'zh-CN' });
  await page.send('Page.addScriptToEvaluateOnNewDocument', {
    source: `${hostBridgeSource({ endpoint: discovery.endpoint, token: discovery.token }, platform())}\n(${installHelpers.toString()})();`,
  });

  const env0 = environment(version.product, options.window);
  printEnvironment(env0);
  let failed = 0;
  let timedOut = 0;
  for (const tier of tiers) {
    tier.runs = [];
    for (let n = 1; n <= options.runs; n++) {
      const loadBefore = await waitForLoad();
      console.error(`== ${tier.label} fresh load ${n}/${options.runs}, 1-minute load ${loadBefore.toFixed(2)}`);
      await page.send('Page.navigate', { url: `${origin}/` });
      const runStarted = Date.now();
      let timer;
      try {
        const suite = runSuite(page, {
          video: tier.label,
          log: (step) => console.error(`  ${step} done (${((Date.now() - runStarted) / 1000).toFixed(0)} s)`),
        });
        // After a timeout this set is still attached to the page: the next navigation would make it error, so it must not be treated as an unhandled rejection.
        suite.catch(() => {});
        const result = await Promise.race([
          suite,
          new Promise((_, fail) => {
            timer = setTimeout(
              () => fail(Object.assign(new Error(`${RUN_TIMEOUT_MS / 60_000} minutes without finishing`), { timeout: true })),
              RUN_TIMEOUT_MS,
            );
          }),
        ]);
        tier.runs.push({ run: n, loadBefore, loadAfter: loadavg()[0], seconds: Math.round((Date.now() - runStarted) / 1000), ...result });
      } catch (error) {
        if (error?.timeout) timedOut++;
        else failed++;
        const message = error instanceof Error ? error.message : String(error);
        tier.runs.push({ run: n, loadBefore, loadAfter: loadavg()[0], error: message });
        console.error(`${tier.label} run ${n}: ${message}`);
      } finally {
        clearTimeout(timer);
      }
    }
  }
  page.close();

  console.log('');
  printEnvironment(env0, tiers, console.log);
  for (const tier of tiers) console.log(scaleLine(tier));
  console.log('');
  console.log(table(tiers));
  console.log(
    `\nBlocked ${typekit} Typekit requests; ${external.size} other non-local requests${external.size > 0 ? `: ${[...external].slice(0, 5).join(', ')}` : ''}`,
  );
  // The media paths are in the temp directory and are deleted on exit, so they are not written into the results.
  if (options.json)
    writeFileSync(options.json, JSON.stringify({ env: env0, tiers: tiers.map(({ media: _media, ...tier }) => tier) }, null, 1));
  exit(timedOut > 0 ? 2 : failed > 0 ? 1 : 0);
}

function findChrome() {
  if (process.env.CUCCUT_CHROME) return existsSync(process.env.CUCCUT_CHROME) ? process.env.CUCCUT_CHROME : null;
  const mac = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
  if (existsSync(mac)) return mac;
  for (const name of ['google-chrome', 'google-chrome-stable', 'chromium', 'chromium-browser']) {
    const found = spawnSync(process.platform === 'win32' ? 'where' : 'which', [name], { encoding: 'utf8' });
    if (found.status === 0 && found.stdout.trim()) return found.stdout.trim().split(/\r?\n/)[0];
  }
  return null;
}

const sleep = (ms) => new Promise((done) => setTimeout(done, ms));

/** Before a load, wait for the 1-minute load average to drop below the threshold; wait at most LOAD_WAIT_MS, then measure anyway if it never drops. Returns the load at the start of measuring. */
async function waitForLoad() {
  const deadline = Date.now() + LOAD_WAIT_MS;
  while (loadavg()[0] >= LOAD_LIMIT && Date.now() < deadline) await sleep(LOAD_POLL_MS);
  return loadavg()[0];
}

/** A minimal CDP client (Node's built-in WebSocket): send sends a command, on receives events, and ev evaluates an async function body in the page and returns the result. */
async function connect(url) {
  const ws = new WebSocket(url);
  await new Promise((done, fail) => {
    ws.addEventListener('open', done, { once: true });
    ws.addEventListener('error', () => fail(new Error(`Cannot connect to ${url}`)), { once: true });
  });
  let id = 0;
  const pending = new Map();
  const handlers = new Map();
  ws.addEventListener('message', (event) => {
    const message = JSON.parse(event.data);
    if (message.id && pending.has(message.id)) {
      const { done, fail } = pending.get(message.id);
      pending.delete(message.id);
      if (message.error) fail(new Error(`${message.error.message}${message.error.data ? `: ${message.error.data}` : ''}`));
      else done(message.result);
    } else if (message.method) handlers.get(message.method)?.(message.params);
  });
  ws.addEventListener('close', () => {
    for (const { fail } of pending.values()) fail(new Error('Connection to Chrome lost'));
    pending.clear();
  });
  const send = (method, params = {}) =>
    new Promise((done, fail) => {
      const i = ++id;
      pending.set(i, { done, fail });
      ws.send(JSON.stringify({ id: i, method, params }));
    });
  const ev = async (body) => {
    const r = await send('Runtime.evaluate', { expression: `(async () => { ${body} })()`, awaitPromise: true, returnByValue: true });
    if (r.exceptionDetails)
      throw new Error(`Error in page: ${r.exceptionDetails.exception?.description ?? r.exceptionDetails.text}`.slice(0, 1500));
    return r.result?.value;
  };
  return { send, ev, sleep, on: (method, fn) => handlers.set(method, fn), close: () => ws.close() };
}

function environment(chrome, window) {
  const git = (args) => spawnSync('git', args, { cwd: ROOT, encoding: 'utf8' }).stdout?.trim() ?? '';
  const macos = process.platform === 'darwin' ? spawnSync('sw_vers', ['-productVersion'], { encoding: 'utf8' }).stdout?.trim() : '';
  return {
    cpu: cpus()[0]?.model ?? '?',
    cores: cpus().length,
    memoryGB: Math.round(totalmem() / 2 ** 30),
    os: macos ? `macOS ${macos}` : `${type()} ${release()}`,
    chrome,
    commit: git(['rev-parse', '--short', 'HEAD']),
    dirty: git(['status', '--porcelain', '--untracked-files=no']) !== '',
    window,
  };
}

function printEnvironment(env, tiers = null, print = console.error) {
  const loads = tiers
    ? tiers.map((t) => `${t.label} ${t.runs.map((r) => `${r.loadBefore.toFixed(1)}→${r.loadAfter.toFixed(1)}`).join(', ')}`).join('; ')
    : null;
  const inner = tiers?.flatMap((t) => t.runs).find((r) => r.window)?.window;
  print(
    `Environment: ${env.cpu} (${env.cores} cores), ${env.memoryGB} GB, ${env.os}; commit ${env.commit}${env.dirty ? ' (uncommitted changes)' : ''}; ` +
      `${env.chrome} (headless), window ${env.window.width}×${env.window.height}${inner ? `, page ${inner.innerW}×${inner.innerH}` : ''}, Typekit blocked` +
      (loads ? `; 1-minute load (before→after run): ${loads}` : ''),
  );
}

function clock(seconds) {
  const s = Math.round(seconds);
  return `${Math.floor(s / 3600)}:${String(Math.floor((s % 3600) / 60)).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`;
}

function scaleLine(tier) {
  const s = tier.scale;
  const ok = tier.runs.filter((r) => !r.error);
  const paragraphs = spread(ok.map((r) => r.lists.transcript.mounted.setsize));
  const bands = spread(ok.map((r) => r.timeline.fit[0]?.bands));
  const items = Object.values(s.items).reduce((a, b) => a + b, 0);
  const parts = [`${s.items.video ?? 0} video clips`, `${s.items.audio ?? 0} dub blocks`, `${s.items.caption ?? 0} captions`];
  return (
    `${tier.label}: ${s.cues} caption cues, ${s.words} transcript words (${paragraphs || '?'} paragraphs), ${s.translations} translated cues, ` +
    `timeline ${items} items (${parts.join(', ')}) and ${bands || s.cuts} cut bands (${s.cuts} cuts), length ${clock(s.seconds)} (transcript ${clock(s.transcriptSeconds)})`
  );
}

/** The range of a set of numbers: if they are all the same, write one; otherwise write “min–max”. */
function spread(values, unit = '') {
  const v = values.filter((x) => typeof x === 'number');
  if (v.length === 0) return '';
  const lo = Math.min(...v);
  const hi = Math.max(...v);
  return lo === hi ? `${lo}${unit}` : `${lo}–${hi}${unit}`;
}

/** The longest-task range for a set of loads (longtask only reports ≥ 50 ms; none counts as 0): none, all, or “k of N runs”. */
function longest(values) {
  if (values.length === 0) return '—';
  const hit = values.filter((v) => v > 0);
  if (hit.length === 0) return 'no task ≥ 50 ms';
  if (hit.length === values.length) return spread(hit, ' ms');
  return `${hit.length} of ${values.length} runs ${spread(hit, ' ms')}`;
}

/** Rows correspond one-to-one with the M12 baseline table in acceptance spec §4. Each cell is the range across this tier's fresh loads; when the large and small tiers match, write “same as left”. */
function table(tiers) {
  const runsOf = (tier) => tier.runs.filter((r) => !r.error);
  const all = (fn) => tiers.flatMap((t) => runsOf(t).map(fn));
  const viewport = (fn) => spread(all(fn), ' px') || '?';
  const isEnter = (name) => name.endsWith('-to-translation');
  const rows = [
    [
      `Caption list mounted (scrolled to middle, viewport height ${viewport((r) => r.lists.captions.mounted.viewportH)}): rows / elements`,
      (runs) =>
        mounts(
          runs.map((r) => r.lists.captions.mounted),
          ['rows', 'elements'],
        ),
    ],
    [
      `Translation list mounted (viewport height ${viewport((r) => r.lists.translation.mounted.viewportH)}): rows / elements`,
      (runs) =>
        mounts(
          runs.map((r) => r.lists.translation.mounted),
          ['rows', 'elements'],
        ),
    ],
    [
      `Transcript mounted (viewport height ${viewport((r) => r.lists.transcript.mounted.viewportH)}): paragraphs / elements`,
      (runs) =>
        mounts(
          runs.map((r) => r.lists.transcript.mounted),
          ['rows', 'elements'],
        ),
    ],
    [
      `Timeline 100% mounted (viewport width ${viewport((r) => r.timeline['scroll 100%'].mounted.viewportW)}): clips / cut bands / elements`,
      (runs) =>
        mounts(
          runs.map((r) => r.timeline['scroll 100%'].mounted),
          ['clips', 'bands', 'elements'],
        ),
    ],
    [
      'Timeline max zoom mounted: clips / cut bands / elements',
      (runs) =>
        mounts(
          runs.map((r) => r.timeline['scroll max'].mounted),
          ['clips', 'bands', 'elements'],
        ),
    ],
    [
      'Frame interval P95 during continuous scrolling of lists and timeline (100%, max zoom)',
      (runs) => {
        const series = runs.flatMap((r) => [...Object.values(r.lists), r.timeline['scroll 100%'], r.timeline['scroll max']]);
        const p95 = spread(
          series.flatMap((s) => [s.scroll.p95, s.fast.p95]),
          ' ms',
        );
        const over = series.reduce((a, s) => a + s.scroll.over50 + s.fast.over50, 0);
        return `${p95}, ${over === 0 ? 'no frames over 50 ms' : `${over} frames over 50 ms across ${series.length * 2} segments`}`;
      },
    ],
    [
      'Timeline one zoom step (between 100% and the adjacent level)',
      (runs) => longest(runs.flatMap((r) => [...r.timeline.zoomIn, ...r.timeline.zoomOut].map((x) => x.longest))),
    ],
    ['Whole sequence in view (all clips mounted)', (runs) => longest(runs.flatMap((r) => r.timeline.fit.map((x) => x.longest)))],
    [
      'Tab switch: between transcript, captions and elements',
      (runs) =>
        longest(
          runs.flatMap((r) =>
            Object.entries(r.tabs)
              .filter(([name]) => !isEnter(name))
              .flatMap(([, xs]) => xs.map((x) => x.longest)),
          ),
        ),
    ],
    [
      'Tab switch: into translation (source + translation)',
      (runs) =>
        longest(
          runs.flatMap((r) =>
            Object.entries(r.tabs)
              .filter(([name]) => isEnter(name))
              .flatMap(([, xs]) => xs.map((x) => x.longest)),
          ),
        ),
    ],
    [
      'Caption replace all / undo',
      (runs) => {
        const reps = runs.flatMap((r) => r.replace);
        const hits = spread(reps.map((x) => x.hits));
        const bad = reps.filter((x) => x.hitsAfterReplace !== 0 || x.hitsAfterUndo !== x.hits).length;
        return (
          `${hits} hits: ${longest(reps.map((x) => x.replaceAll.longest))} / ${longest(reps.map((x) => x.undo.longest))}` +
          (bad > 0 ? `(${bad} checks failed: hits remained after replace, or the count did not return to the original after undo)` : '')
        );
      },
    ],
  ];
  const out = [`| Item | ${tiers.map((t) => t.label).join(' | ')} |`, `| --- | ${tiers.map(() => '---').join(' | ')} |`];
  const runsByTier = tiers.map(runsOf);
  for (const [label, cell] of rows) {
    const cells = runsByTier.map((runs) => {
      if (runs.length === 0) return 'not finished';
      try {
        return cell(runs);
      } catch {
        return '?';
      }
    });
    for (let i = cells.length - 1; i > 0; i--) if (runsByTier[i].length > 0 && cells[i] === cells[i - 1]) cells[i] = 'same as left';
    out.push(`| ${label} | ${cells.join(' | ')} |`);
  }
  out.push('');
  out.push(
    'Notes: mount counts are taken from each fresh load scrolled to the middle (timeline 100% and max zoom each at 50%); scrolling covers 40 px and 200 px per frame, 240 frames each; ' +
      'action cells give the range of the longest task (longtask, reported only if ≥ 50 ms) across runs; "k of N runs" means the other runs had no task ≥ 50 ms; ' +
      '"between transcript, captions and elements" covers the three pairs that leave translation; "into translation" covers the three pairs from transcript, captions and elements into source + translation, two rounds each.',
  );
  return out.join('\n');
}

function mounts(list, keys) {
  return keys.map((key) => spread(list.map((m) => m[key]))).join(' / ');
}
