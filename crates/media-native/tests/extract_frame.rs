//! Real-media acceptance for single-frame extraction.
//!
//! The fixtures and judging tools are in `common`, shared with the sequential frame stream acceptance. They are three single-color segments (red / green / blue, each with a horizontal luminance ramp) freshly generated by ffmpeg. The assertions are readable color predicates rather than pixel goldens. Per `docs/design/bcf/cuccut-format-spec.md` §15.1, decoded video frame pixels only promise semantic equivalence plus tolerance, and thumbnails are not golden.
//!
//! The cross-backend comparison (native ↔ ffmpeg) uses the shared SSIM implementation in `ccut-render::imgcmp` (8×8 sliding window, per-channel RGBA, sample variance + 4× downsampling, consistent with `ccut ssim` / `ccut compare`). Before WP5b converged, three places each had their own mutually inconsistent minimal implementation. It is pulled in only as a dev-dependency and does not enter the production binary.
//!
//! If ffmpeg cannot be detected, the whole test is skipped. This is the repository's existing courtesy: no fixture is not a failure.

mod common;

use media_native::{available, extract_frame_rgba, scaled_height};
use render_raster::imgcmp;

use common::{HEIGHT, SEGMENT, WIDTH, dominant, ffmpeg_frame, fixture, to_pixmap};

#[test]
fn each_segment_yields_its_own_colour() {
    if !available() {
        return;
    }
    let Some((_dir, media)) = fixture() else {
        return;
    };
    for (time, expected) in [(0.5, "red"), (1.5, "green"), (2.5, "blue")] {
        let frame = extract_frame_rgba(&media, time, 168).expect("native frame extraction");
        assert_eq!(dominant(&frame), expected, "t={time} should yield the {expected} segment");
    }
}

/// Time precision: within ±1 frame on either side of a segment boundary, segments must not bleed into each other. Exact, zero-tolerance frame extraction is the whole point of this assertion. If it fell back to the "nearest keyframe", 1.033s would pick up the red frame before 1.0s (GOP = 30 frames).
#[test]
fn frames_do_not_bleed_across_a_segment_boundary() {
    if !available() {
        return;
    }
    let Some((_dir, media)) = fixture() else {
        return;
    };
    let frame_step = 1.0 / 30.0;
    // The last frame of the red segment (29/30 ≈ 0.967s) and the first frame of the green segment (1.0s).
    let last_red = SEGMENT - frame_step * 0.5;
    let first_green = SEGMENT + frame_step * 0.5;
    assert_eq!(
        dominant(&extract_frame_rgba(&media, last_red, 168).expect("native frame extraction")),
        "red",
        "t={last_red} is still inside the red segment"
    );
    assert_eq!(
        dominant(&extract_frame_rgba(&media, first_green, 168).expect("native frame extraction")),
        "green",
        "t={first_green} has entered the green segment"
    );
}

#[test]
fn frames_are_scaled_to_the_requested_width_with_an_even_height() {
    if !available() {
        return;
    }
    let Some((_dir, media)) = fixture() else {
        return;
    };
    for width in [84_u32, 168, 320, 640] {
        let frame = extract_frame_rgba(&media, 0.5, width).expect("native frame extraction");
        assert_eq!(frame.width, width, "width must match the requested value exactly");
        assert_eq!(
            frame.height,
            scaled_height(WIDTH, HEIGHT, width),
            "height must follow the source aspect ratio and be rounded to an even number"
        );
        assert_eq!(frame.height % 2, 0);
        assert_eq!(
            frame.data.len(),
            frame.width as usize * frame.height as usize * 4
        );
        assert!(
            frame.data.chunks_exact(4).all(|pixel| pixel[3] == 255),
            "video frames must return opaque alpha"
        );
    }
}

/// Cross-decode-backend comparison: for the same file at the same t, SSIM between the native frame and the ffmpeg frame (the cross-backend semantic equivalence criterion of §15.1; the diagnostic must carry the identifiers of both backends).
///
/// The criterion uses [`imgcmp::Comparison::ssim_downsampled`], with the threshold set to the **0.95** written in the text of §15.1. Before WP6a this was 0.90. At that time the fixture used two **hard-edge** color blocks, white on the left and black on the right, to keep SSIM from degenerating on solid colors. But 4:2:0 chroma has only half the horizontal resolution: AVFoundation and swscale use different chroma upsampling and scaling interpolation on that edge, and the sliding-window SSIM magnified it to a score of 0.91. (In the same measurement, `flat_max_deviation` was only 3–13, so the color matrices were already very close; the score loss was all at the edges.) After the fixture was changed to a continuous luminance ramp (`common::fixture`), the structure term still has content but there are no hard edges at all. Measured:
///
/// | t | ssim | ssim_downsampled | maxDeviation | flatMaxDeviation |
/// | --- | --- | --- | --- | --- |
/// | 0.5s (red segment) | 0.9846 | 0.9847 | 15 | 13 |
/// | 1.5s (green segment) | 0.9779 | 0.9765 | 15 | 13 |
/// | 2.5s (blue segment) | 0.9827 | 0.9872 | 14 | 5 |
///
/// The remaining difference is the normal divergence between the two paths' YUV→RGB matrix implementations and their scalers, which is exactly the quantity §15.1 wants to measure. `edge_share` is close to 100% on the ramp (almost every pixel's 3×3 neighborhood is non-constant). That is the normal reading of this diagnostic field for continuous gradients, not a regression signal.
#[test]
fn native_frames_match_the_ffmpeg_fallback_within_the_cross_backend_tolerance() {
    const SSIM_FLOOR: f64 = 0.95;
    if !available() {
        return;
    }
    let Some((_dir, media)) = fixture() else {
        return;
    };
    for time in [0.5_f64, 1.5, 2.5] {
        let native = extract_frame_rgba(&media, time, 168).expect("native frame extraction");
        let Some(reference) = ffmpeg_frame(&media, time, 168) else {
            return;
        };
        assert_eq!(
            (native.width, native.height),
            (reference.width, reference.height),
            "both paths must agree on the size contract"
        );
        let measured = imgcmp::compare(&to_pixmap(&native), &to_pixmap(&reference))
            .expect("size was already asserted equal above");
        assert!(
            measured.ssim_downsampled >= SSIM_FLOOR,
            "t={time}s cross-backend SSIM (4× downsampled) {:.4} is below {SSIM_FLOOR} (backend {} vs ffmpeg, full-resolution ssim={:.4}, per-channel max deviation {}, flat-region max deviation {})",
            measured.ssim_downsampled,
            media_native::backend(),
            measured.ssim,
            measured.max_deviation,
            measured.flat_max_deviation,
        );
        println!(
            "t={time}s ssim={:.4} ssim_downsampled={:.4} max={} flat={} edge={:.3}%",
            measured.ssim,
            measured.ssim_downsampled,
            measured.max_deviation,
            measured.flat_max_deviation,
            measured.edge_share * 100.0
        );
    }
}

#[test]
fn a_missing_file_is_an_error_not_a_panic() {
    if !available() {
        return;
    }
    let dir = tempfile::tempdir().unwrap();
    assert!(extract_frame_rgba(&dir.path().join("nope.mp4"), 0.0, 168).is_err());
}
