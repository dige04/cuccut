import { resolve } from 'node:path';
import optimizeLocales from '@react-aria/optimize-locales-plugin';
import react from '@vitejs/plugin-react';
import { defineConfig } from 'vite';
import { LOCALE_TAGS } from '../../packages/protocol/src/i18n.ts';
import { pdfLicenses } from '../../tools/pdf-licenses.ts';
import { thirdPartyNotices } from '../../tools/third-party-notices.ts';
import { s2Styles, s2StylesChunk } from '../../tools/s2-styles.ts';
import tailwindcss from '@tailwindcss/vite';
import { cuccutTheme, s2ShimAlias } from '../../tools/cuccut-theme.ts';

/**
 * The web client (architecture design §4.8): the same UI package and the same Vite plugins as the desktop renderer; the output is static files,
 * served by the Runtime's Web service on a loopback port (`npm run build:web`).
 */
export default defineConfig({
  root: resolve(import.meta.dirname, 'src'),
  // The page is only served by the Web service at the site root path.
  base: '/',
  // The preview's WASM is imported with `?inline` as a data URL. Vite does not treat .wasm as an asset by default, so this has to be stated explicitly.
  assetsInclude: ['**/*.wasm', '**/*.bcmap', '**/*.pfb'],
  // CucCut: S2 imports go through the theme shim (agentcut's button language on S2 components).
  resolve: { alias: [s2ShimAlias()] },
  plugins: [
    // S2's style macro must be processed first (in development, the S2 styles are additionally merged and deduplicated; see tools/s2-styles.ts).
    ...s2Styles(),
    tailwindcss(),
    // CucCut: agentcut's palette over every S2 colour (tools/cuccut-theme.ts).
    cuccutTheme(),
    pdfLicenses(resolve(import.meta.dirname, '../..')),
    thirdPartyNotices(resolve(import.meta.dirname, '../..')),
    react(),
    { ...optimizeLocales.vite({ locales: Object.values(LOCALE_TAGS) }), enforce: 'pre' },
  ],
  build: {
    target: 'es2022',
    outDir: resolve(import.meta.dirname, 'dist'),
    emptyOutDir: true,
    rollupOptions: {
      output: {
        // The CSS generated by S2, the S2 AI components, and the style macro is combined into one file, to avoid cascade-order problems from splitting it by chunk.
        manualChunks: s2StylesChunk,
      },
    },
  },
});
