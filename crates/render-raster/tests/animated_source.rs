//! Source conformance for `AnimatedImage` (GIF / APNG / animated WebP) (design §10 stage 6).
//!
//! Each of the four acceptance criteria maps to an executable assertion:
//! * **Direct seek at any time** — `random_seek_needs_no_warm_up`
//! * **Sequential and shuffled sampling are identical** — `shuffled_sampling_equals_sorted_sampling`
//! * **All sub-resources go into the hash** — `the_fingerprint_covers_every_frame_and_delay`
//! * **No network during rendering, and the source holds no incremental clock** — `sampling_takes_only_a_shared_reference`
//!   plus “repeated sampling is byte-for-byte identical” (the source has no mutable state it could hold)
//!
//! The fixtures are **generated by a program** (`write_animated_fixtures`, `#[ignore]`) and land in
//! `core/fixtures/animated/`. This follows the same approach as `core/fixtures/gen.sh`, but uses a crate rather than ffmpeg: precise control over per-frame disposal / blend / loop count is needed, and ffmpeg cannot provide it.
//! `animated_fixtures_are_up_to_date` is the everyday gate, catching “changed the generator but forgot to write to disk”.

use render_raster::source::animated_image::{
    AnimatedFormat, AnimatedImage, AnimatedImageBudgetExceeded,
};
use render_raster::source::{MediaTime, PrepareCtx, SourceLoop, VisualSource, frame_index};
use sha2::{Digest, Sha256};
use std::path::{Path, PathBuf};

mod fixture_gen;

fn fixture_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/animated")
}

fn load(name: &str) -> AnimatedImage {
    let path = fixture_dir().join(name);
    let bytes = std::fs::read(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    AnimatedImage::decode(name, &bytes, &PrepareCtx::default())
        .unwrap_or_else(|e| panic!("decode {name}: {e:#}"))
}

fn frame_digest(pixmap: &tiny_skia::Pixmap) -> String {
    let mut h = Sha256::new();
    h.update(pixmap.data());
    // The sha2 0.11 digest (hybrid-array) has no `LowerHex`, so it is written out byte by byte, giving the same value as `{:x}` in v2.
    let hex: String = h.finalize().iter().map(|b| format!("{b:02x}")).collect();
    hex[..16].to_string()
}

