import { R } from './render-copy.ts';
import { RenderPlanner } from './render-planner.ts';

let loading: Promise<RenderPlanner> | null = null;
/** The recorded load has already finished (`fresh` does not drop it). */
let loaded = false;

/**
 * If this long passes without a result (neither success nor failure), log a dev message and forget the recorded attempt, so the next preview reloads. If that attempt's result arrives later, previews waiting on it still work. Without this, one stuck load would leave every preview opened afterwards stuck in loading.
 */
const LOAD_STALL_MS = 30_000;

/**
 * Fonts published with the render kernel (`npm run build:wasm` copies them from `crates/render-raster/assets/fonts`): only the address is taken, and the file is read when it is used. The fonts are over 20 MB, so they are not inlined into the bundle.
 */
const FONT_URLS = import.meta.glob<string>('./generated/fonts/*.ttf', { query: '?url', import: 'default', eager: true });

/**
 * The preview's WASM (generated by `npm run build:wasm`), a separate chunk loaded on demand. A glob is used instead of a literal dynamic import: without a build this is an empty object, and the error is thrown only at load time, so the rest of the UI still loads. (A literal import pointing to a file that does not exist would make both the dev server and the build fail outright.)
 */
const WASM = import.meta.glob<string>('./generated/preview.wasm', { query: '?inline', import: 'default' });

/**
 * Loads the preview's frame planner. The WASM is generated by `npm run build:wasm` and inlined into the bundle as a data URL, so the dev server and the packaged file:// page take the same path: no separate file fetch, and no need to add `data:` to the CSP connect-src. All fonts are read in the order the WASM gives, and injected in one go before the planner is handed out (each injection rebuilds the renderer in WASM). The text box for new text is also measured by it, and measuring waits for it to load (`components/editor/text-measure.ts`). Loaded only once. If it fails, or gets no result for a long time (`LOAD_STALL_MS`), the next attempt tries again.
 * `fresh` (the “retry” when a preview is stuck): if the recorded attempt has no result yet, do not wait for it; reload. An attempt that has already loaded is still used.
 */
export function loadRenderPlanner(options: { fresh?: boolean } = {}): Promise<RenderPlanner> {
  const wasm = WASM['./generated/preview.wasm'];
  if (!wasm) return Promise.reject(new Error(R.planner.wasmMissing));
  if (options.fresh && !loaded) loading = null;
  if (loading) return loading;
  const attempt = wasm().then(async (url) => {
    const planner = await RenderPlanner.instantiate(decodeDataUrl(url));
    planner.addFonts(await Promise.all(planner.fontFiles().map(readFont)));
    return planner;
  });
  loading = attempt;
  loaded = false;
  const timer = setTimeout(() => {
    if (loading !== attempt) return;
    console.warn(`[preview] 渲染内核载入 ${LOAD_STALL_MS / 1000} 秒还没有结果：之后的预览重新载入`); // i18n-ignore: dev log
    loading = null;
  }, LOAD_STALL_MS);
  attempt.then(
    () => {
      clearTimeout(timer);
      if (loading === attempt) loaded = true;
    },
    () => {
      clearTimeout(timer);
      if (loading === attempt) loading = null;
    },
  );
  return attempt;
}

async function readFont(name: string): Promise<Uint8Array> {
  const url = FONT_URLS[`./generated/fonts/${name}`];
  if (!url) throw new Error(R.fonts.notFound(name));
  // The packaged page under file:// does not support fetch for this protocol, so XHR is used instead.
  if (new URL(url, location.href).protocol === 'file:') return readWithXhr(url);
  const response = await fetch(url);
  if (!response.ok) throw new Error(R.fonts.unreadable(name, response.status));
  return new Uint8Array(await response.arrayBuffer());
}

function readWithXhr(url: string): Promise<Uint8Array> {
  return new Promise((resolve, reject) => {
    const request = new XMLHttpRequest();
    request.open('GET', url);
    request.responseType = 'arraybuffer';
    request.onload = () => {
      // file:// has no HTTP status; on success it is 0 (200 in Electron).
      const ok = request.status === 0 || request.status === 200;
      if (ok && request.response instanceof ArrayBuffer) resolve(new Uint8Array(request.response));
      else reject(new Error(R.fonts.unreadableUrl(url)));
    };
    request.onerror = () => reject(new Error(R.fonts.unreadableUrl(url)));
    request.send();
  });
}

function decodeDataUrl(url: string): Uint8Array<ArrayBuffer> {
  const binary = atob(url.slice(url.indexOf(',') + 1));
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}
