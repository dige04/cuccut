import type { RiskLevel } from './access.ts';
import type { ToolEffect, ToolSurface } from './services.ts';

/**
 * The Agent-facing tool catalog is given to the CLI through the gateway (architecture design §3.5, §4.1; command and protocol spec §4.1): `catalog.list` lists the catalog, and `catalog.call` calls a tool by name. The catalog is the same one as the agents and MCP services in the session (`ToolCatalog`); the principal is `LocalPrincipal`: the user operates in the terminal themselves, writes are recorded as `user_local`, and they do not go through CucCut's approval. It is served only to `cli` and `desktop` connections, and is not on the Web service's allowlist.
 */

/** A tool in the catalog. `inputSchema` is the JSON Schema of its arguments (generated by zod). */
export interface CatalogTool {
  name: string;
  title: string;
  description: string;
  inputSchema: Record<string, unknown>;
  annotations?: { readOnlyHint?: boolean; destructiveHint?: boolean; idempotentHint?: boolean };
  /** The default risk level of the action (`TOOL_RISK` in architecture design §3.12; it depends on the arguments, and the per-call value takes precedence). */
  risk: RiskLevel;
  /** Effect: `query` is read-only, `mutation` changes state, `job` returns a `jobId`, `destructive` cannot be undone (the CLI needs `--yes`). */
  effect: ToolEffect;
  /** One to three minimal call examples (JSON arguments), shown by `help <command>` and `spec`. */
  examples: ReadonlyArray<{ title: string; args: Record<string, unknown> }>;
  /** The surfaces it appears on; the terminal's catalog always includes `cli`. */
  surfaces: ReadonlyArray<ToolSurface>;
  /** The field name for the CLI's only positional argument. */
  positional?: string;
  /** A CLI shortcut switch: `--<flag>` is the same as giving `field` this value (`transcribe --replace` is `--target replace`). Not included in MCP's tools/list. */
  cliSwitches?: ReadonlyArray<CatalogCliSwitch>;
}

/** A CLI shortcut switch (`CatalogTool.cliSwitches`). A flag must not share a name with a field-derived flag or a flag reserved by the CLI. */
export interface CatalogCliSwitch {
  flag: string;
  field: string;
  value: string | number | boolean;
}

/**
 * The result of `edits_ops` (the operation families and the description, JSON Schema and example of each operation): the CLI's offline snapshot carries it, and `spec edits.<op>` can give it without connecting to the Runtime.
 */
export interface CatalogEditOperations {
  conventions: string;
  families: { family: string; operations: { type: string; family: string; description: string; schema: Record<string, unknown>; example: Record<string, unknown> }[] }[];
}

/** The CLI's offline catalog snapshot (`apps/cli/src/generated/catalog.json`, generated by `tools/catalog-snapshot.ts`): the `catalog.list` result plus the operation catalog. */
export interface CatalogSnapshot extends CatalogListResult {
  editOps: CatalogEditOperations;
}

export interface CatalogListResult {
  /** The contract version for tool names and arguments; the three Agent-facing surfaces (the tool bridge, the MCP service and the CLI) share one version number (`MCP_INTERFACE_VERSION`). */
  interfaceVersion: string;
  tools: CatalogTool[];
}

export interface CatalogCallParams {
  name: string;
  /** Tool arguments (JSON), validated against the tool's schema; if they do not fit, `{ ok: false, error: { code: 'INVALID_ARGUMENTS' } }`. */
  args: unknown;
  /** The CLI's working directory (absolute path): relative paths (materials, export targets, video directories) are resolved against it, and the project is searched upward from it. */
  cwd: string;
  /** The explicitly given project directory (absolute path; the CLI resolves `--project` against the cwd beforehand); if not given, it searches upward from `cwd` for `.ccut/project.json`. */
  project?: string | null;
}

/** A tool's refusal: exactly the same as the `error` in an MCP tool result (`code` is a closed error code; `next` / `remedy` / `retryability` say how to recover). */
export interface CatalogToolError {
  code: string;
  message: string;
  [key: string]: unknown;
}

/** The result of a call: the tool's result object, or a tool-level refusal. Gateway-level refusals (wrong connection kind, wrong argument shape) are still RPC errors. */
export type CatalogCallResult = { ok: true; result: unknown } | { ok: false; error: CatalogToolError };

/**
 * The result of `catalog.agentSkill`: the instruction document for external Agents (`skills/cuccut/`, Agent-facing design §8.6), with all its files rendered for the CLI surface; `cuccut skill install` writes them as is into the host's skills directory.
 */
export interface CatalogAgentSkill {
  interfaceVersion: string;
  /** The skill's id, which is also the directory name in the host's skills directory (`cuccut`). */
  id: string;
  /** The source directory the Runtime reads (absolute local path). */
  sourceDir: string;
  /** Relative paths (`/`-separated) and contents, sorted by path. */
  files: { path: string; content: string }[];
}

/**
 * How tool names and argument names are written on the CLI (Agent-facing design §4.1). The CLI command tree and flags, the `next` that the Runtime renders for the CLI, the instruction renderer (`agent-skill-renderer.ts`), and the craft sync script share this one set of rules:
 *
 * - A tool name `<noun>_<verb>` becomes `<noun> <verb>`; the `_` in a multi-word verb becomes `-` (`videos_import_package` → `videos import-package`).
 *   A name without `_` is a top-level verb, and it is the same on both sides (`transcribe`).
 * - A field name in `camelCase` becomes the flag `--kebab-case` (`documentId` → `--document-id`).
 */
export interface ToolCommandName {
  /** The noun group; null for top-level verbs. */
  noun: string | null;
  verb: string;
  /** How it is written on the command line (excluding `cuccut`): `videos import-package`, `export`. */
  display: string;
}

export function toolCommandName(name: string): ToolCommandName {
  const [head, ...rest] = name.split('_');
  if (rest.length === 0) return { noun: null, verb: head!, display: head! };
  const verb = rest.join('-');
  return { noun: head!, verb, display: `${head} ${verb}` };
}

/** Field name → flag name (excluding `--`): `documentId` → `document-id`. */
export function fieldFlagName(field: string): string {
  return field.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

/**
 * Turns tool names in a piece of text into CLI commands (`videos_list` → `cuccut videos list`): it converts only names in `names` that contain `_`, matching whole words.
 * Top-level verbs are the same on both sides and are often ordinary words, so they are left alone.
 */
export function renderCliToolNames(text: string, names: readonly string[]): string {
  const compound = names.filter((name) => name.includes('_')).sort((a, b) => b.length - a.length);
  if (compound.length === 0) return text;
  const pattern = new RegExp(`(?<![A-Za-z0-9_])(${compound.join('|')})(?![A-Za-z0-9_])`, 'g');
  return text.replace(pattern, (name) => `cuccut ${toolCommandName(name).display}`);
}
