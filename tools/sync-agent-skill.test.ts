import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import type { CatalogTool } from '@cuccut/protocol';
import {
  COMMON_OPS,
  REPO_ROOT,
  buildAgentSkillSync,
  diffAgentSkillSync,
  writeAgentSkillSync,
  type SyncInputs,
} from './sync-agent-skill.ts';

const FIXTURE = path.join(REPO_ROOT, 'packages/runtime-core/src/skills/testing/agent-skill-fixture');
const SCRIPT = path.join(REPO_ROOT, 'tools/sync-agent-skill.ts');
const AGENT = 'skills/cuccut';
const BUILTIN = `${AGENT}/built-in-skills`;

function tool(name: string, effect: CatalogTool['effect'], surfaces: CatalogTool['surfaces'] = ['agent', 'mcp', 'cli']): CatalogTool {
  return { name, title: name, description: name, inputSchema: { type: 'object' }, risk: 'low', effect, examples: [], surfaces };
}

/** A fixed small directory: the assertions do not change with the explanatory text in the real directory. */
const INPUTS: SyncInputs = {
  cliTools: [
    tool('assets_import', 'mutation'),
    tool('captions_create', 'mutation'),
    tool('documents_put', 'mutation'),
    tool('documents_read', 'query'),
    tool('edits_apply', 'mutation'),
    tool('edits_ops', 'query'),
    tool('jobs_wait', 'query'),
    tool('transcribe', 'job'),
    tool('videos_frames', 'query'),
    tool('videos_inspect', 'query'),
    tool('videos_import_package', 'mutation', ['agent', 'cli']),
  ],
  agentToolNames: [
    'assets_import',
    'captions_create',
    'documents_put',
    'documents_read',
    'downloads_save',
    'edits_apply',
    'edits_ops',
    'jobs_wait',
    'skills_read',
    'transcribe',
    'videos_frames',
    'videos_import_package',
    'videos_inspect',
  ],
  editOps: {
    conventions: '',
    families: [
      {
        family: 'timeline',
        operations: COMMON_OPS.map(({ op }) => ({
          type: op,
          family: 'timeline',
          description: `${op}(…)}: First sentence of ${op}. Not the second one.`,
          schema: {},
          example: { type: op },
        })),
      },
    ],
  },
  exitCodes: {
    CAPABILITY_NOT_CONFIGURED: 2,
    RUNTIME_UNAVAILABLE: 3,
    INVALID_ARGUMENTS: 4,
    UNKNOWN_TOOL: 4,
    RUNTIME_NOT_OWNED: 1,
    RUNTIME_IN_USE: 1,
    AGENT_SKILL_NOT_FOUND: 1,
    AGENT_SKILL_INVALID: 1,
    SOME_FAILURE: 1,
  },
};

const dirs: string[] = [];
afterEach(() => {
  for (const dir of dirs.splice(0)) fs.rmSync(dir, { recursive: true, force: true });
});

/** The fixture is copied to a temp directory, with generated blocks cleared and the craft copy removed, starting from "never synced". */
function freshFixture(): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cuccut-sync-agent-skill-'));
  dirs.push(root);
  fs.cpSync(FIXTURE, root, { recursive: true });
  const agentDir = path.join(root, AGENT);
  for (const id of ['demo-polish', 'demo-chapters']) fs.rmSync(path.join(agentDir, 'references/craft', `${id}.md`), { force: true });
  for (const file of ['references/catalog/editing.md', 'references/conventions.md', 'references/mcp.md']) {
    const abs = path.join(agentDir, file);
    fs.writeFileSync(abs, fs.readFileSync(abs, 'utf8').replace(/(<!-- generated: [a-z-]+ -->\n)[\s\S]*?(<!-- \/generated -->)/g, '$1$2'));
  }
  return root;
}

const read = (root: string, rel: string) => fs.readFileSync(path.join(root, rel), 'utf8');

describe('skill document sync', () => {
  it('craft copy: strip front matter, body\'s level-one heading becomes the title, references become an appendix, tool names and skills_read rewritten per CLI surface', () => {
    const root = freshFixture();
    const result = buildAgentSkillSync(root, INPUTS);
    expect(result.files.get(`${AGENT}/references/craft/demo-polish.md`)).toBe(
      [
        '<!-- Generated by tools/sync-agent-skill.ts from skills/cuccut/built-in-skills/demo-polish/. Do not edit by hand: change the source files, then run npm run build:agent-skill -->',
        '',
        '# Polish a transcript',
        '',
        '> A craft for tests - polish a transcript. Only for the renderer and sync script tests.',
        '',
        'Before writing, read this page\'s appendix "Base text and defaults": the base text and defaults are there.',
        '',
        '1. Read the transcript with `cuccut documents read` and confirm sourceBasis.',
        '2. Edit word for word and write back to the same document with `cuccut documents put`; afterwards check the revision with `cuccut videos inspect`.',
        "3. At delivery, tell the user the file's path (the terminal has no downloads directory step: the file is where you wrote it).",
        '4. Hand chapters to [demo-chapters](demo-chapters.md); that step uses setChapters of `cuccut edits apply`.',
        '',
        '## Appendix: Base text and defaults',
        '',
        '### Base text',
        '',
        'Read it through first and settle the base text. When there is a lot to change, the method is in appendix "Base text and defaults" on this page; do not fetch anything else.',
        '',
        '### Defaults',
        '',
        '- Fix only typos and punctuation.',
        '',
      ].join('\n'),
    );
    const chapters = result.files.get(`${AGENT}/references/craft/demo-chapters.md`)!;
    expect(chapters).toContain('When the transcript is not polished yet, first read [`references/craft/demo-polish.md`](demo-polish.md).');
    // A trailing full stop does not block the tool name.
    expect(chapters).toContain('in one go with setChapters of `cuccut edits apply`.');
    // Tools that exist only in the session: those with a fallback (downloads_save) are swapped out without a warning; those without one are left as-is, with a warning.
    expect(result.warnings).toEqual([]);
    fs.appendFileSync(path.join(root, BUILTIN, 'demo-polish/SKILL.md'), '\nUpdate tasks_contract at the end.\n');
    const withContract = buildAgentSkillSync(root, { ...INPUTS, agentToolNames: [...INPUTS.agentToolNames, 'tasks_contract'] });
    expect(withContract.warnings).toEqual([
      `${BUILTIN}/demo-polish/SKILL.md:16: tasks_contract exists only in CucCut sessions and has no CLI command; left as is`,
    ]);
  });

  it('craft references the shared directory page: generates resolvable links, does not copy tables, sync fails when the target is missing', () => {
    const root = freshFixture();
    const shared = `${AGENT}/references/catalog/voice-language-rates.md`;
    const body = '# Shared speech rates\n\n| Language | Rate |\n| --- | --- |\n| English | 2.1 |\n';
    fs.writeFileSync(path.join(root, shared), body);
    fs.appendFileSync(
      path.join(root, BUILTIN, 'demo-polish/SKILL.md'),
      '\nUse `skills_read` to read `cuccut-catalog-voice-language-rates`.\n',
    );
    const result = buildAgentSkillSync(root, INPUTS);
    const craft = result.files.get(`${AGENT}/references/craft/demo-polish.md`)!;
    expect(craft).toContain('[cuccut-catalog-voice-language-rates](../catalog/voice-language-rates.md)');
    expect(craft).not.toContain('| English | 2.1 |');
    expect(read(root, shared)).toBe(body);
    expect(result.warnings).toEqual([]);
    fs.rmSync(path.join(root, shared));
    expect(() => buildAgentSkillSync(root, INPUTS)).toThrow('references/catalog/voice-language-rates.md');
  });

  it('leading verbs are also rewritten per CLI surface; a word joined to -, /, or ., or followed by :, is not a tool name; no backticks added inside code blocks; English words, code and values are left unchanged', () => {
    const root = freshFixture();
    fs.appendFileSync(
      path.join(root, BUILTIN, 'demo-polish/SKILL.md'),
      [
        '',
        'For a link, use transcribe with `url` (or pass `transcribe: true`); chapters are in [demo-chapters](demo-chapters.md), transcribe-only outputs go under transcribe/, and the script is transcribe.ts.',
        '',
        '```bash',
        'transcribe --url x',
        '```',
        '',
        // The same word in English prose, CSS, or values is not a tool name.
        'Every transcribe job is English prose here; the',
        'transcribe (at a line start) too, and the element type `transcribe`.',
        '',
        '```js',
        "parts.push('transcribe(-50%)'); transcribe(1);",
        '```',
        '',
      ].join('\n'),
    );
    const result = buildAgentSkillSync(root, INPUTS);
    const text = result.files.get(`${AGENT}/references/craft/demo-polish.md`)!;
    expect(text).toContain(
      'For a link, use `cuccut transcribe` with `url` (or pass `transcribe: true`); chapters are in [demo-chapters](demo-chapters.md), transcribe-only outputs go under transcribe/, and the script is transcribe.ts.',
    );
    expect(text).toContain('```bash\ncuccut transcribe --url x\n```');
    expect(text).toContain('Every transcribe job is English prose here; the\ntranscribe (at a line start) too, and the element type `transcribe`.');
    expect(text).toContain("```js\nparts.push('transcribe(-50%)'); transcribe(1);\n```");
    expect(result.warnings).toEqual([]);
  });

  it('three generated blocks: common-ops, error-codes split by surface, and tool-map for the CLI surface only', () => {
    const root = freshFixture();
    const files = buildAgentSkillSync(root, INPUTS).files;
    const editing = files.get(`${AGENT}/references/catalog/editing.md`)!;
    for (const { op, label } of COMMON_OPS) {
      expect(editing).toContain(`**${label}** (\`${op}\`): First sentence of ${op}.\n\n\`\`\`json\n{"type":"${op}"}\n\`\`\``);
    }
    expect(editing).not.toContain('Not the second one');
    expect(editing).toContain('Caption layers are created with {{tool:captions_create}}');

    const conventions = files.get(`${AGENT}/references/conventions.md`)!;
    expect(conventions).toContain(
      ['<!-- generated: error-codes -->', '<!-- surface: cli -->', '| Error code | Exit code | Next step |', '| --- | --- | --- |'].join('\n'),
    );
    expect(conventions).toContain('| `CAPABILITY_NOT_CONFIGURED` | 2 |');
    expect(conventions).toContain('| `INVALID_ARGUMENTS` `UNKNOWN_TOOL` | 4 |');
    // Lines with exit code 1 are split by next step: lines in the same sentence are merged into one line. Where no separate next step is written, the line uses the sentence with “other error codes”.
    expect(conventions).toContain("| `RUNTIME_NOT_OWNED` `RUNTIME_IN_USE` | 1 | The Runtime is not this CLI's to stop");
    expect(conventions).toContain('| `AGENT_SKILL_NOT_FOUND` `AGENT_SKILL_INVALID` | 1 | The agent guide cannot be installed');
    expect(conventions).toMatch(/\| `SOME_FAILURE` \| 1 \| Failed or cancelled\./);
    expect(conventions).toContain('<!-- surface: agent -->\n| Error code | Next step |\n| --- | --- |\n| `CAPABILITY_NOT_CONFIGURED` |');

    // The mcp.md block is already inside the cli section, so it is not wrapped again.
    const mcp = files.get(`${AGENT}/references/mcp.md`)!;
    expect(mcp).toContain(
      '<!-- generated: tool-map -->\n| MCP tool | CLI command | Effect |\n| --- | --- | --- |\n| `assets_import` | `cuccut assets import` | mutation |',
    );
    expect(mcp).toContain('| `transcribe` | `cuccut transcribe` | job |');
    expect(mcp).toContain('Only in the CLI, not on MCP: `cuccut videos import-package`.\n<!-- /generated -->');
  });

  it('after writing, --check matches; README.md is not managed by the script; extra craft pages count as stale and are deleted', () => {
    const root = freshFixture();
    const craftDir = path.join(root, AGENT, 'references/craft');
    fs.writeFileSync(path.join(craftDir, 'old-one.md'), '# Stale\n');
    const readme = read(root, `${AGENT}/references/craft/README.md`);

    const first = buildAgentSkillSync(root, INPUTS);
    expect(first.stale).toEqual([`${AGENT}/references/craft/old-one.md`]);
    expect(writeAgentSkillSync(root, first)).toContain(`${AGENT}/references/craft/old-one.md`);
    expect(fs.existsSync(path.join(craftDir, 'old-one.md'))).toBe(false);
    expect(read(root, `${AGENT}/references/craft/README.md`)).toBe(readme);
    expect(diffAgentSkillSync(root, buildAgentSkillSync(root, INPUTS))).toEqual([]);
  });

  it('an unrewritable skills_read phrasing errors, with source file and line number', () => {
    const root = freshFixture();
    fs.appendFileSync(path.join(root, BUILTIN, 'demo-chapters/SKILL.md'), '\nWhen unsure, look at something else with `skills_read`.\n');
    expect(() => buildAgentSkillSync(root, INPUTS)).toThrow(
      /^skills\/cuccut\/built-in-skills\/demo-chapters\/SKILL\.md:13：This `skills_read` phrasing cannot be rewritten for the CLI face/,
    );
  });

  it('after generation both surfaces must render: fails when a placeholder is wrong', () => {
    const root = freshFixture();
    fs.appendFileSync(path.join(root, AGENT, 'references/workflows.md'), '\n4. {{tool:no_such}}\n');
    expect(() => buildAgentSkillSync(root, INPUTS)).toThrow('references/workflows.md:9：{{tool:no_such}}：CLI 面的目录里没有这个工具');
  });

  it('command line: exit code 1 when --check mismatches, 0 after writing', () => {
    const root = freshFixture();
    const run = (...args: string[]) => spawnSync(process.execPath, [SCRIPT, '--root', root, ...args], { encoding: 'utf8' });
    const before = run('--check');
    expect(before.status).toBe(1);
    expect(before.stderr).toContain('The agent guide is out of date with its sources');
    expect(run().status).toBe(0);
    expect(run('--check').status).toBe(0);
  });

  it('the repo\'s skill doc matches its source (run npm run build:agent-skill when it does not)', () => {
    expect(diffAgentSkillSync(REPO_ROOT, buildAgentSkillSync(REPO_ROOT))).toEqual([]);
  });
});
