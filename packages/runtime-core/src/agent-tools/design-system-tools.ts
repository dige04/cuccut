export class DesignSystemTools implements ToolSet {
  readonly schemas = schemas;
  readonly definitions = DEFINITIONS;
  readonly #deps: DesignSystemToolsDeps;

  constructor(deps: DesignSystemToolsDeps) {
    this.#deps = deps;
  }

  dispatch(name: string, args: unknown, principal: ToolPrincipal): Promise<unknown> {
    switch (name as ToolName) {
      case 'design_system_check':
        return this.#check(args as Args<'design_system_check'>, principal);
      case 'design_system_import_asset':
        return this.#importAsset(args as Args<'design_system_import_asset'>, principal);
      default:
        return Promise.reject(new ToolError('UNKNOWN_TOOL', `No such tool: ${name}`));
    }
  }

  async #check(args: Args<'design_system_check'>, principal: ToolPrincipal) {
    const { scope } = this.#deps;
    const access = scope.authorize(principal, false);
    // Validate even when design-system.json is missing or malformed: the problems go in the list, and the agent fixes them from it.
    const system = await this.#system(access, args.path, false);
    const result = await checkDesignSystem(system.dir);
    const problems = result.issues.length;
    if (problems === 0) scope.recordDesignSystem?.(access, { target: system.target, title: result.title });
    return {
      path: system.target.path,
      title: result.title,
      namespace: result.namespace,
      problems,
      ...(problems > 0 ? { issues: result.issues.slice(0, MAX_LISTED_ISSUES) } : {}),
      ...(result.notes.length > 0 ? { notes: result.notes.slice(0, MAX_LISTED_NOTES) } : {}),
      ...(problems > MAX_LISTED_ISSUES ? { more: `${problems - MAX_LISTED_ISSUES} more not listed: fix these first, then check again` } : {}),
      notChecked: `${result.notChecked.join(', ')} are generated by the editor on save and were not checked; whether components render and how they look were not checked (no rendering).`,
      next:
        problems > 0
          ? 'Fix the files per issues (file is a path relative to the design system directory; "." is the whole directory), then call design_system_check again until problems is 0. notes need no changes.'
          : 'No problems: a card for this design system now appears in the thread, and the user can open it to view and edit. notes need no changes. Tell the user in a sentence or two what you made; do not paste file contents again.',
    };
  }

  async #importAsset(args: Args<'design_system_import_asset'>, principal: ToolPrincipal) {
    const { scope, designSystem } = this.#deps;
    const access = scope.authorize(principal, true);
    if (args.group !== undefined && !isAssetGroupName(args.group)) {
      throw new ToolError('INVALID_GROUP', 'group must be an asset group folder name: at most 80 characters, no / \\ or control characters, no leading or trailing whitespace, not . or ..');
    }
    const system = await this.#system(access, args.system, true);
    const file = await this.#sourceFile(access, args.path);
    const type = contentTypeOf(file.path);
    const approval = await scope.confirm(access, {
      tool: 'design_system_import_asset',
      targets: [system.dir],
      ...confirmSummary(RcAgentTools.designSystemImportAssetSummary({ file: args.path, system: system.target.path || '.' })),
    });
    const bytes = await fs.readFile(file.path);
    if (bytes.byteLength !== file.size) throw new ToolError('FILE_CHANGED', 'The file changed while awaiting confirmation: call again');
    const uploaded = await designSystem.designSystemStore(system.dir).putBlob(bytes, type);
    const base = path.basename(file.path);
    // The path the record restores to (the original `restoreFilesFromIndex`): in a group it is assets/<group>/<name>; in blobs the name is the path, with fonts under fonts/ and everything else under assets/.
    const name = args.group !== undefined ? base : `${type.startsWith('font/') ? DESIGN_SYSTEM_PATHS.fontsDir : DESIGN_SYSTEM_PATHS.assetsDir}${base}`;
    const key = encodeIndexKey(name);
    const groupKey = args.group !== undefined ? encodeIndexKey(args.group) : undefined;
    const record = { name, blob: uploaded.id, size: uploaded.sizeBytes, type };
    const restoredAs = args.group !== undefined ? `${DESIGN_SYSTEM_PATHS.assetsDir}${args.group}/${name}` : name;
    return {
      src: uploaded.url,
      record,
      key,
      ...(groupKey !== undefined ? { groupKey } : {}),
      indexPath: groupKey !== undefined ? ['assetGroups', groupKey, 'files', key] : ['blobs', key],
      restoredAs,
      bytes: uploaded.sizeBytes,
      contentType: type,
      ...approvalField(approval),
      next:
        (groupKey !== undefined
          ? `Write record into design-system.json at assetGroups.${groupKey}.files.${key} (if the group does not exist yet, first create {"name": ${JSON.stringify(args.group)}, "order": [], "files": {}} and add "${groupKey}" to groups); `
          : `Write record into design-system.json at blobs.${key}; `) +
        `the asset shows in the editor as ${restoredAs}, so do not write a file with the same name at that path (the file wins and the record is ignored). When other files reference it, write src as is (${uploaded.url}). Call design_system_check when done.`,
    };
  }

  /**
   * The caller's design system directory: relative to the working directory and inside the session's source directory. With
   * `requireSystem`, its design-system.json either does not exist yet (being created) or is a design system index with a
   * migration marker. Returns the real path and the FileTarget used to open it (source directory + relative path, `/`-separated).
   */
  async #system(access: ToolAccess, given: string, requireSystem: boolean) {
    const { scope } = this.#deps;
    const { root, scope: source } = await scope.createRoot(access, undefined, { locate: true });
    const absolute = path.resolve(scope.fileBase(access), given);
    const relNative = path.relative(root, absolute);
    if (relNative === '..' || relNative.startsWith(`..${path.sep}`) || path.isAbsolute(relNative)) throw systemOutside();
    let dir: string;
    try {
      dir = await resolveDeckDir(root, relNative);
    } catch (error) {
      if (!(error instanceof RpcError)) throw error;
      if (error.code === 'not-found') throw new ToolError('DESIGN_SYSTEM_NOT_FOUND', `No such directory in the working directory: ${given}`);
      throw systemOutside();
    }
    // A directory without design-system.json is a design system being created (the original allows uploads to an empty design
    // system). One with the file must be an index with a migration marker: the editor opens unmarked ones read-only, and the
    // skill says not to write into them (docs/design/canvas §10.1).
    if (requireSystem && (await fs.lstat(path.join(dir, DESIGN_SYSTEM_FILE)).catch(() => null))) {
      const index = await readDesignSystemJson(dir);
      if (!isDesignSystemIndex(index) || !hasDesignSystemMarker(index)) {
        throw new ToolError(
          'NOT_A_DESIGN_SYSTEM',
          `The design-system.json in ${given} is not a design system index with a createdOnFiles or convertedFrom marker: the editor opens it read-only (or does not recognize it); do not import into it, tell the user`,
        );
      }
    }
    const relPath = relNative.split(path.sep).filter(Boolean).join('/');
    return { dir, target: { ...source, path: relPath } };
  }

  /** The file to import: a regular file in the working directory (judged by real path, not through a symlink), of an allowed type, within the size limit. */
  async #sourceFile(access: ToolAccess, given: string): Promise<{ path: string; size: number }> {
    const base = await fs.realpath(this.#deps.scope.fileBase(access));
    if (path.isAbsolute(given) || path.win32.isAbsolute(given) || given.split(/[\\/]+/).includes('..')) throw fileOutside();
    const resolved = path.resolve(base, given);
    if (resolved === base || !inside(resolved, base)) throw fileOutside();
    const stat = await fs.lstat(resolved).catch(() => null);
    if (!stat) throw new ToolError('FILE_NOT_FOUND', `No such file in the working directory: ${given}`);
    if (stat.isSymbolicLink()) throw new ToolError('PATH_IS_SYMLINK', 'path is a symbolic link: give the file it points to, inside the working directory');
    if (!stat.isFile()) throw new ToolError('NOT_A_FILE', 'path must be a regular file (not a directory)');
    const dirReal = await fs.realpath(path.dirname(resolved));
    if (!inside(dirReal, base)) throw fileOutside();
    const file = path.join(dirReal, path.basename(resolved));
    const ext = file.slice(file.lastIndexOf('.') + 1).toLowerCase();
    if (!DESIGN_SYSTEM_ASSET_EXTENSIONS.has(ext) || file.lastIndexOf('.') < 0) {
      throw new ToolError(
        'UNSUPPORTED_ASSET_TYPE',
        'Only png, jpg, jpeg, gif, webp, svg, mp4, webm, pdf, woff2, woff, ttf, otf can be imported, judged by extension. Write text files such as README, css, js and json directly into the design system directory',
      );
    }
    const limit = designSystemUploadLimit(contentTypeOf(file));
    if (stat.size > limit) {
      throw new ToolError('FILE_TOO_LARGE', `The file is ${formatBytes(stat.size)}, over the ${formatBytes(limit)} limit${ext === 'svg' ? ' (SVG)' : ''}: compress or shrink it first`, {
        bytes: stat.size,
        limit,
      });
    }
    return { path: file, size: stat.size };
  }
}

function systemOutside(): ToolError {
  return new ToolError('PATH_OUTSIDE_WORKSPACE', 'The design system must be a directory in the session\'s working directory (a relative path, not inside a hidden or dependency directory, not through a symlink pointing elsewhere)');
}

function fileOutside(): ToolError {
  return new ToolError('PATH_OUTSIDE_WORKSPACE', 'path must be a file in this session\'s working directory (a relative path, no .., not through a symlink pointing elsewhere)');
}
