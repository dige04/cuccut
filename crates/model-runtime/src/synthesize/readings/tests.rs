use super::*;
use crate::synthesize::types::VoiceSpec;

fn reading(start: usize, end: usize, text: &str, origin: Origin) -> Reading {
    Reading {
        start,
        end,
        reading: text.to_owned(),
        origin,
    }
}

fn pieces(list: &[&str]) -> HashSet<String> {
    list.iter().map(|s| (*s).to_owned()).collect()
}

#[test]
fn data_files_match_the_readme_digests() {
    use sha2::{Digest, Sha256};
    let readme = include_str!("data/README.md");
    for (name, bytes) in [
        ("heteronyms.txt.z", &include_bytes!("data/heteronyms.txt.z")[..]),
        ("homophones.txt.z", &include_bytes!("data/homophones.txt.z")[..]),
    ] {
        let digest: String = Sha256::digest(bytes).iter().map(|b| format!("{b:02x}")).collect();
        let row = readme
            .lines()
            .find(|line| line.starts_with(&format!("| `{name}` |")))
            .unwrap_or_else(|| panic!("README has no {name} row"));
        assert!(row.contains(&digest), "{name} SHA-256 does not match README: {digest}");
    }
}

#[test]
fn tone3_spelling_matches_every_heteronym_default() {
    // The phrase table and the single-character table store strict initials and finals; the TONE3 spelling reassembled from them must match, character for character, the polyphone table generated by pypinyin.
    // The only strict initial/final combinations that cannot be reassembled are these interjections (`yo` and `o` are both zero-initial + `o`; `hm` / `n` / `m` have no final). They are not in the context list, and the phrase table does not use them to fix readings.
    const LOSSY: &str = "噷唷嗯喲呣哟";
    let mut checked = 0;
    for (&c, entry) in HETERONYMS.iter() {
        assert!(entry.all.len() >= 2 && entry.all[0] == entry.default, "{c}");
        if LOSSY.contains(c) {
            assert!(!is_context_heteronym(c), "{c}");
            continue;
        }
        let id = pinyin::default_syllable(c).unwrap_or_else(|| panic!("{c} has no default reading"));
        assert_eq!(pinyin::tone3(id), entry.default, "{c}");
        checked += 1;
    }
    assert!(checked > 6000, "{checked}");
    assert_eq!(readings_of('绿'), ["lv4", "lu4"]);
    assert_eq!(readings_of('句')[0], "ju4");
    assert_eq!(readings_of('略'), ["lve4"]);
    assert_eq!(readings_of('远'), ["yuan3"]);
}

